#!/usr/bin/env python3
"""Generate learn/data/3d/chairs.js: for each model the two chair conformers (same atom order; b is the ring flip of a)
built by tools/chairs.py, plus the ring atom order and the heavy substituent atoms. Coordinates are computed, never typed."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import chairs as C
from rdkit import Chem

# id -> (smiles, positions, relationship). Stereo: with this SMILES template ('@','@') = trans, ('@','@@') = cis
# (verified below against a fresh embedding: side of the ring mean plane).
MODELS = {
    "cyclohexane": ("C1CCCCC1", None, None),
    "methylcyclohexane": ("CC1CCCCC1", None, None),
    "dm-trans-12": ("C[C@H]1[C@H](C)CCCC1", "1,2", "trans"),
    "dm-cis-12": ("C[C@H]1[C@@H](C)CCCC1", "1,2", "cis"),
    "dm-trans-13": ("C[C@H]1C[C@H](C)CCC1", "1,3", "trans"),
    "dm-cis-13": ("C[C@H]1C[C@@H](C)CCC1", "1,3", "cis"),
    "dm-trans-14": ("C[C@H]1CC[C@H](C)CC1", "1,4", "trans"),
    "dm-cis-14": ("C[C@H]1CC[C@@H](C)CC1", "1,4", "cis"),
}
out = {}
for mid, (smi, pos, rel) in MODELS.items():
    p = C.build_pair(smi, angles=(109.3, 112.8))   # ring C-C-C angles held in 109-113 degrees
    mol = Chem.AddHs(Chem.MolFromSmiles(smi))
    R = C.six_ring(mol)
    if rel:
        assert C.face_label(smi) == rel, (mid, C.face_label(smi))
    subs = [a.GetIdx() for a in mol.GetAtoms() if a.GetAtomicNum() > 1 and a.GetIdx() not in R]
    out[mid] = {"smiles": smi, "positions": pos, "rel": rel, "ring": R, "subs": subs, "a": p["a"], "b": p["b"],
                "eA": round(p["ea"], 3), "eB": round(p["eb"], 3)}
    print(mid, "ring", R, "subs", subs, "E(a),E(b) kcal/mol (MMFF)", round(p["ea"], 2), round(p["eb"], 2))
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "3d", "chairs.js")
with open(path, "w") as f:
    f.write("// GENERATED by learn/tools/gen_chairs.py (RDKit + MMFF, ring flip built computationally) - do not edit by hand.\n"
            "// Each model: two chair conformers with the SAME atom order (a = lower MMFF energy, b = the ring-flipped chair).\n"
            "export default " + json.dumps(out, indent=1) + ";\n")
print("wrote", path)
