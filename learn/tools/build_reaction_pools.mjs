// Builds engine/reaction-pools.js: for each reaction practice mode, every problem it can make, as small integer rows (substrate index, reagent-variant index, stereo flag)
// grouped by card (by template for the two-step roadmap). The settings of the reaction practice pages filter these pools, so the landing page can count problems without
// running the engines. A row is kept only when the mode's own builder returns a problem for it. tests/reaction-modes.mjs recomputes every pool with the builders and fails
// when this file is stale, so run this again after changing a drill pool, a card, a template or a builder:
//   node learn/tools/build_reaction_pools.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ready } from '../engine/chem.js';
import { DRILL, DRILL_IDS, solveCard, problemFor } from '../engine/generators-predict.js';
import * as M from '../engine/generators-reaction-modes.js';
import { productStereo } from '../engine/reaction-attrs.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'engine', 'reaction-pools.js');
const r0 = () => 0.5;
await ready();

const skipped = (v, s) => (v.skip || []).includes(s);
/** Rows [si, vi, stereo] of the cards whose builder returns a problem. */
function comboRows(cards, build, stereoOf) {
  const out = {};
  for (const cardId of cards) {
    const e = DRILL[cardId], rows = [];
    e.subs.forEach((sub, si) => e.variants.forEach((v, vi) => {
      if (skipped(v, sub)) return;
      const p = build(cardId, sub, v);
      if (!p) return;
      rows.push(si, vi, stereoOf(cardId, sub, v, p) ? 1 : 0);
    }));
    if (rows.length) out[cardId] = rows;
  }
  return out;
}
const solved = (cardId, sub, v) => M.solveForModes(cardId, sub, v);
const pools = {};
pools['predict-product'] = comboRows(DRILL_IDS, (c, s, v) => { try { return problemFor(c, s, v, r0); } catch (e) { return null; } }, (c, s, v) => productStereo(solveCard(c, s, v, r0).products));
pools['guess-reagent'] = comboRows(M.ENGINE_CARDS, (c, s, v) => M.buildGuessReagent({ cardId: c, sub: s, v }, r0), (c, s, v) => productStereo(solved(c, s, v).products));
pools['guess-reactant'] = comboRows(M.ENGINE_CARDS, (c, s, v) => M.buildGuessReactant({ cardId: c, sub: s, v }, r0), (c, s, v) => productStereo(solved(c, s, v).products));
pools['stereo-outcome'] = comboRows(M.STEREO_CARDS, (c, s, v) => M.buildStereoOutcome({ cardId: c, sub: s, v }, r0), (c, s, v, p) => p.stereo.C !== 'none');
const two = {};
for (const t of M.TEMPLATES) {
  const rows = [];
  for (const ch of M.chainsOf(t)) {
    const p = M.buildTwoStep(ch, r0);
    if (!p) continue;
    rows.push(DRILL[t.A].subs.indexOf(ch.start), DRILL[t.A].variants.indexOf(ch.a.v), DRILL[t.B].variants.indexOf(ch.b.v), productStereo(p.products) ? 1 : 0);
  }
  if (rows.length) two[t.id] = rows;
}
pools['two-step'] = two;

const line = (k, rows) => `    ${JSON.stringify(k)}: [${rows.join(',')}]`;
let src = '// GENERATED by tools/build_reaction_pools.mjs: do not edit. The problems each reaction practice mode can make, as integer rows grouped by card (by template for two-step):\n';
src += '//   combo modes: [substrate index in DRILL[card].subs, reagent-variant index in DRILL[card].variants, 1 if the product shows stereo] repeated;\n';
src += '//   two-step: [start index in DRILL[A].subs, variant index of A, variant index of B, stereo flag] repeated. "wont-work" is the curated case list (no rows needed).\n';
src += 'export const POOL_DATA = {\n';
src += Object.keys(pools).map((m) => `  ${JSON.stringify(m)}: {\n${Object.keys(pools[m]).map((k) => line(k, pools[m][k])).join(',\n')}\n  }`).join(',\n');
src += '\n};\n';
fs.writeFileSync(OUT, src);
const n = (m) => Object.values(pools[m]).reduce((s, r) => s + r.length / (m === 'two-step' ? 4 : 3), 0);
console.log('wrote', OUT, Object.keys(pools).map((m) => `${m}: ${n(m)}`).join(', '), `(${(src.length / 1024).toFixed(1)} KB)`);
