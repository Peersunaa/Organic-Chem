// Picks the seeds of the three worked examples of every question type and writes data/question-type-seeds.js:
//   node learn/tools/pick_master_seeds.mjs            (all types)   |   node learn/tools/pick_master_seeds.mjs predict-hx assign-rs   (only these; the rest of the file is kept)
// Example i of a type comes from source i % sources.length (so the three examples spread over the sources); the seed is the first one, counting up from 1, whose problem is
// a TYPED or PICKED answer (kind 'input', or 'choice' with exactly one right option) that has a worked line (derive or deriveHtml): widget problems are left to the practice.
// A source whose generator does not know the task (an 'unknown task' error) is skipped and the next source of the type is tried; a type with no usable source gets [].
// Reaction engines are slow, so this takes a few minutes. Re-run it after a generator or a type's sources change (tests/master.mjs fails when an example stops being valid).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ready } from '../engine/chem.js';
import { TYPES } from '../data/question-types.js';
import { buildExample } from '../engine/master.js';
import { SEEDS as OLD } from '../data/question-type-seeds.js';

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'data', 'question-type-seeds.js');
const MAX_SEED = 400;
const only = process.argv.slice(2);

/** Is this problem usable as a read-only worked example? */
export function usable(p) {
  if (!p || !(p.prompt || p.promptHtml) || !(p.derive || p.deriveHtml)) return false;
  if (p.kind === 'input') return p.answer !== undefined && p.answer !== null && String(p.answer) !== '';
  if (p.kind === 'choice') return Array.isArray(p.options) && p.options.filter((o) => o.correct).length === 1;
  return false;
}
const key = (p) => JSON.stringify([p.prompt, p.smiles, p.answer, (p.options || []).map((o) => o.text || o.smiles)]);

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await ready();
  const seeds = {};
  for (const t of TYPES) {
    if (only.length && !only.includes(t.id)) { seeds[t.id] = OLD[t.id] || []; continue; }
    const dead = new Set(), got = [], seen = new Set();
    for (let i = 0; i < 3; i++) {
      let done = false;
      for (let k = 0; k < t.sources.length && !done; k++) {
        const si = (i + k) % t.sources.length;
        if (dead.has(si)) continue;
        for (let seed = 1; seed <= MAX_SEED && !done; seed++) {
          let p;
          try { p = buildExample(t.sources[si], seed); } catch (e) {
            if (/^unknown task/.test(e.message)) { dead.add(si); console.log(`  ${t.id}: source ${si} (${t.sources[si].gen}) skipped: ${e.message}`); break; }
            continue;
          }
          if (!usable(p) || seen.has(key(p))) continue;
          seen.add(key(p)); got.push({ src: si, seed }); done = true;
        }
      }
    }
    seeds[t.id] = got;
    console.log(`${t.id}: ${got.map((g) => g.src + '@' + g.seed).join(' ') || '(none)'}`);
  }
  const body = TYPES.map((t) => `  '${t.id}': [${(seeds[t.id] || []).map((g) => `{ src: ${g.src}, seed: ${g.seed} }`).join(', ')}]`).join(',\n');
  fs.writeFileSync(OUT, `// GENERATED by tools/pick_master_seeds.mjs: the seeds of the three worked examples of every question type (data/question-types.js): example i = sources[src] built with mulberry32(seed).\n// Do not edit by hand; run the tool again after a generator or a type's sources change.\nexport const SEEDS = {\n${body}\n};\n`);
  console.log('wrote ' + OUT);
}
