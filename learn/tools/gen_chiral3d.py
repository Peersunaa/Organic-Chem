#!/usr/bin/env python3
"""Lesson 15: solid 3D models of chiral (and one achiral) molecules and their TRUE mirror images.
Each model: AddHs -> EmbedMolecule(seed) -> MMFFOptimizeMolecule, best of several conformers; the mirror image is the SAME coordinates reflected
through the plane x = 0 (x -> -x), never built by hand. Both are checked here with RDKit's new CIP labeler (the 3D structure's label is
read back from the coordinates, the mirror must have the opposite label, an achiral molecule has none) and written to
learn/data/3d/chiral.js as { id: { smiles, name, center, label, achiral, molblock, mirror } }.
Heavy atoms keep the SMILES atom numbers; the hydrogens come after them."""
import json, os, sys
from rdkit import Chem
from rdkit.Chem import AllChem, rdCIPLabeler

MODELS = {
    # id: (smiles, name)
    "chfclbr":       ("F[C@H](Cl)Br", "bromochlorofluoromethane"),
    "ch2clbr":       ("ClCBr", "bromochloromethane"),
    "butan-2-ol":    ("C[C@@H](O)CC", "butan-2-ol"),
    "2-bromobutane": ("CC[C@@H](C)Br", "2-bromobutane"),
    "alanine":       ("C[C@H](N)C(=O)O", "alanine"),
    "glyceraldehyde": ("OC[C@@H](O)C=O", "glyceraldehyde"),
    "lactic-acid":   ("C[C@@H](O)C(=O)O", "lactic acid"),
    "2-chlorobutane": ("CC[C@H](C)Cl", "2-chlorobutane"),
}

def cip_from_block(mb):
    m = Chem.MolFromMolBlock(mb, removeHs=False)
    Chem.AssignStereochemistryFrom3D(m)
    rdCIPLabeler.AssignCIPLabels(m)
    return {a.GetIdx(): a.GetProp("_CIPCode") for a in m.GetAtoms() if a.HasProp("_CIPCode")}

def reflect(mb):
    L = mb.split("\n")
    n = int(L[3][:3])
    for i in range(n):
        l = L[4 + i]
        x = float(l[0:10])
        L[4 + i] = f"{-x:10.4f}" + l[10:]
    return "\n".join(L)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data", "3d")
res = {}
for mid, (smi, name) in MODELS.items():
    m0 = Chem.MolFromSmiles(smi)
    want = {a.GetIdx(): a.GetProp("_CIPCode") for a in (lambda mm: (rdCIPLabeler.AssignCIPLabels(mm), mm.GetAtoms())[1])(Chem.Mol(m0)) if a.HasProp("_CIPCode")}
    m = Chem.AddHs(m0)
    ids = list(AllChem.EmbedMultipleConfs(m, 20, randomSeed=15))
    resu = AllChem.MMFFOptimizeMoleculeConfs(m)
    best = min(range(len(ids)), key=lambda i: resu[i][1])
    mb = Chem.MolToMolBlock(m, confId=ids[best])
    mir = reflect(mb)
    got, gotm = cip_from_block(mb), cip_from_block(mir)
    if want:
        (idx, lab), = want.items()
        assert got == want, (mid, got, want)
        assert gotm == {idx: "S" if lab == "R" else "R"}, (mid, gotm)
        center, label = idx, lab
    else:
        assert got == {} and gotm == {}, (mid, got, gotm)
        center, label = None, None
    res[mid] = {"smiles": smi, "name": name, "center": center, "label": label, "achiral": not want, "molblock": mb, "mirror": mir}
with open(os.path.join(out, "chiral.js"), "w") as f:
    f.write("// GENERATED by learn/tools/gen_chiral3d.py - do not edit by hand.\n// Each mirror image is the same RDKit/MMFF coordinates reflected through x = 0.\nexport default " + json.dumps(res, indent=1) + ";\n")
print("wrote", ", ".join(f"{k}({v['label'] or 'achiral'})" for k, v in res.items()))
